// Rebuilds generated assets from the data files:
//   js/data/flags-data.js every flag as minified SVG, from the region-flags
//                        package (Wikimedia Commons, public domain), except
//                        any file in tools/flag-overrides/, which wins.
//   js/data/map-data.js  projected world map + a location for every flag.
// Run with:  npm install  &&  npm run build-data
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoNaturalEarth1, geoPath, geoArea, geoCentroid } from "d3-geo";
import { optimize } from "svgo";
import { COUNTRIES } from "../js/data/countries.js";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const iso = require("i18n-iso-countries");

// ---------- flags ----------
const srcDir = path.join(root, "node_modules/region-flags/svg");
const overrideDir = path.join(root, "tools/flag-overrides");
const flagSvg = {};
let total = 0;
for (const c of COUNTRIES) {
  const override = path.join(overrideDir, `${c.code}.svg`);
  const src = fs.existsSync(override) ? override : path.join(srcDir, `${c.code}.svg`);
  if (!fs.existsSync(src)) throw new Error(`No flag file for ${c.code}`);
  let svg = fs.readFileSync(src, "utf8");
  svg = optimize(svg, {
    multipass: true,
    floatPrecision: 3,
    plugins: [{ name: "preset-default", params: { overrides: { removeViewBox: false } } }],
  }).data;
  // Make sure every flag has a viewBox so it scales cleanly.
  if (!/viewBox=/.test(svg)) {
    const w = svg.match(/<svg[^>]*\bwidth="([\d.]+)/)?.[1];
    const h = svg.match(/<svg[^>]*\bheight="([\d.]+)/)?.[1];
    if (w && h) svg = svg.replace("<svg", `<svg viewBox="0 0 ${w} ${h}"`);
  }
  // Keep width/height (they give <img> its true aspect ratio); CSS sets the display size.
  if (!/<svg[^>]*\bwidth=/.test(svg)) {
    const vb = svg.match(/viewBox="([^"]+)"/)[1].split(/[\s,]+/).map(Number);
    svg = svg.replace("<svg", `<svg width="${vb[2]}" height="${vb[3]}"`);
  }
  flagSvg[c.code] = svg;
  total += svg.length;
}
const codes = new Set(COUNTRIES.map((c) => c.code));
fs.writeFileSync(path.join(root, "js/data/flags-data.js"),
  "// GENERATED by tools/build-data.mjs. Flag artwork from Wikimedia Commons (public domain).\n" +
  "// To fix a flag, put a corrected SVG in tools/flag-overrides/<CODE>.svg and run npm run build-data.\n" +
  "export const FLAG_SVG = " + JSON.stringify(flagSvg, null, 0).replace(/","/g, '",\n"') + ";\n");
console.log(`flags: ${COUNTRIES.length} files, ${(total / 1024).toFixed(0)} KB`);

// ---------- map ----------
const W = 1000, H = 520;
const projection = geoNaturalEarth1().fitExtent([[6, 6], [W - 6, H - 6]], { type: "Sphere" });
const pathGen = geoPath(projection).digits(1);

function codeFor(f) {
  if (f.properties?.name === "Kosovo") return "XK";
  if (f.properties?.name === "Taiwan") return "TW";
  if (f.id == null) return null;
  return iso.numericToAlpha2(String(f.id).padStart(3, "0")) || null;
}

const t110 = JSON.parse(fs.readFileSync(path.join(root, "node_modules/world-atlas/countries-110m.json")));
const t50 = JSON.parse(fs.readFileSync(path.join(root, "node_modules/world-atlas/countries-50m.json")));
const f110 = feature(t110, t110.objects.countries).features;
const f50 = feature(t50, t50.objects.countries).features;

const paths = {};
let other = "";
for (const f of f110) {
  const code = codeFor(f);
  if (f.properties?.name === "Antarctica") continue;
  const d = pathGen(f);
  if (!d) continue;
  if (code && codes.has(code)) paths[code] = (paths[code] || "") + d;
  else other += d;
}

// Location of the main landmass of each feature.
function mainCentroid(f) {
  if (f.geometry.type !== "MultiPolygon") return geoCentroid(f);
  let best = null, bestA = -1;
  for (const poly of f.geometry.coordinates) {
    const g = { type: "Polygon", coordinates: poly };
    const a = geoArea(g);
    if (a > bestA) { bestA = a; best = g; }
  }
  return geoCentroid(best);
}
// Hand-placed [longitude, latitude] for places the atlas can't locate well.
const MANUAL = {
  "GB-ENG": [-1.5, 52.6], "GB-SCT": [-4.2, 56.8], "GB-WLS": [-3.8, 52.3],
  TK: [-171.8, -9.2], PN: [-130.1, -25.07], CX: [105.69, -10.45], CC: [96.87, -12.17],
  GI: [-5.35, 36.14], TV: [179.2, -8.5], NR: [166.93, -0.53], MO: [113.55, 22.19],
  HK: [114.17, 22.32], SX: [-63.06, 18.04], NU: [-169.87, -19.05], NF: [167.95, -29.04],
  BM: [-64.75, 32.3], KI: [173.0, 1.4], SH: [-5.7, -15.95], MV: [73.5, 4.2], VA: [12.45, 41.9],
  MC: [7.42, 43.74], SM: [12.45, 43.94], LI: [9.55, 47.15], AD: [1.55, 42.55], MT: [14.4, 35.9],
  FR: [2.4, 46.6], US: [-98.5, 39.5], NL: [5.3, 52.2], NO: [9.0, 61.5], DK: [9.3, 56.0],
  GB: [-2.0, 54.0], PF: [-149.4, -17.65], FM: [158.2, 6.9], MH: [171.2, 7.1], PW: [134.58, 7.5],
};
const points = {};
for (const f of f50) {
  const code = codeFor(f);
  if (code && codes.has(code)) points[code] = mainCentroid(f);
}
for (const c of COUNTRIES) {
  const ll = MANUAL[c.code] || points[c.code];
  if (!ll) throw new Error(`No map location for ${c.code}`);
  const [x, y] = projection(ll);
  points[c.code] = [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}
// Bounding boxes for countries with drawn shapes (used by map questions).
const boxes = {};
for (const f of f110) {
  const code = codeFor(f);
  if (!code || !codes.has(code)) continue;
  // Use the main landmass so e.g. France isn't zoomed to include Guiana.
  const main = f.geometry.type === "MultiPolygon"
    ? { type: "Polygon", coordinates: f.geometry.coordinates.reduce((a, p) => geoArea({ type: "Polygon", coordinates: p }) > geoArea({ type: "Polygon", coordinates: a }) ? p : a) }
    : f.geometry;
  const [[x0, y0], [x1, y1]] = pathGen.bounds(main);
  boxes[code] = [x0, y0, x1, y1].map((v) => Math.round(v));
}
const sphere = pathGen({ type: "Sphere" });
const out = `// GENERATED by tools/build-data.mjs from Natural Earth (public domain). Do not edit by hand.
export const MAP = ${JSON.stringify({ width: W, height: H, sphere, other, paths, points, boxes })};
`;
fs.writeFileSync(path.join(root, "js/data/map-data.js"), out);
console.log(`map: ${Object.keys(paths).length} shapes, ${Object.keys(points).length} points, ${(out.length / 1024).toFixed(0)} KB`);
