// Writes sw.js: the offline cache list plus a version hash of every file,
// so iPads pick up changes automatically the next time they're online.
// Run after any change:  npm run build-sw
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const include = ["index.html", "manifest.webmanifest", "css", "js", "icons", "audio"];
const files = [];
const walk = (rel) => {
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) return;
  if (fs.statSync(abs).isDirectory()) for (const f of fs.readdirSync(abs).sort()) walk(path.join(rel, f));
  else if (!/(^|\/)\.|\.svg$/.test(rel)) files.push(rel.split(path.sep).join("/"));
};
include.forEach(walk);
const keep = files.filter((f) => !f.startsWith("icons/icon-1024") && !f.endsWith(".md"));
const hash = crypto.createHash("sha256");
for (const f of keep) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest("hex").slice(0, 12);

const sw = `// GENERATED by tools/build-sw.mjs — makes The Flag Vault work offline.
const VERSION = "${version}";
const CACHE = "flag-vault-" + VERSION;
const FILES = ${JSON.stringify(["./", ...keep])};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("flag-vault-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
      if (res.ok && new URL(e.request.url).origin === location.origin) {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
      }
      return res;
    }).catch(() => caches.match("./")))
  );
});
`;
fs.writeFileSync(path.join(root, "sw.js"), sw);
console.log(`sw.js: ${keep.length} files, version ${version}`);
